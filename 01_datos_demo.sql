WITH NUMEROS AS (
    SELECT TOP (300) ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS NRO
    FROM sys.all_objects
)
INSERT INTO dbo.dsc_zona_geografica (ID_ZONA, REGION, PROVINCIA, LOCALIDAD)
SELECT
    N.NRO AS ID_ZONA,
    CASE N.NRO % 4 WHEN 0 THEN 'AMBA' WHEN 1 THEN 'CENTRO' WHEN 2 THEN 'NORTE' ELSE 'SUR' END AS REGION,
    CONCAT('PROVINCIA ', N.NRO % 12) AS PROVINCIA,
    CONCAT('LOCALIDAD ', N.NRO) AS LOCALIDAD
FROM NUMEROS AS N;

WITH NUMEROS AS (
    SELECT TOP (2000000) ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS NRO
    FROM sys.all_objects AS A
    CROSS JOIN sys.all_objects AS B
),
OT_BASE AS (
    SELECT
        N.NRO AS ID_OT,
        DATEADD(MINUTE, -ABS(CHECKSUM(NEWID())) % 525600, CAST('2026-10-30' AS DATETIME2(0))) AS FECHA_CREACION,
        ABS(CHECKSUM(NEWID())) % 100 AS AZAR
    FROM NUMEROS AS N
)
INSERT INTO dbo.ordenes_trabajo_facts
    (ID_OT, ID_CLIENTE, ID_ZONA, ID_RED, ID_TIPO_TRABAJO, FECHA_CREACION, FECHA_CIERRE, ESTADO)
SELECT
    B.ID_OT,
    1000000 + ABS(CHECKSUM(NEWID())) % 800000 AS ID_CLIENTE,
    1 + ABS(CHECKSUM(NEWID())) % 300 AS ID_ZONA,
    1 + B.AZAR % 3 AS ID_RED,
    1 + B.AZAR % 6 AS ID_TIPO_TRABAJO,
    B.FECHA_CREACION,
    CASE WHEN B.AZAR < 85 THEN DATEADD(HOUR, 2 + B.AZAR, B.FECHA_CREACION) END AS FECHA_CIERRE,
    CASE WHEN B.AZAR < 85 THEN 'CERRADA' WHEN B.AZAR < 95 THEN 'EN CURSO' ELSE 'CANCELADA' END AS ESTADO
FROM OT_BASE AS B;

WITH PASOS AS (
    SELECT PASO, ESTADO
    FROM (VALUES (1, 'CREADA'), (2, 'AGENDADA'), (3, 'REPROGRAMADA'), (4, 'EN CURSO'), (5, 'CERRADA')) AS P (PASO, ESTADO)
)
INSERT INTO dbo.estados_ot_facts (ID_EVENTO, ID_OT, ESTADO, FECHA_ESTADO)
SELECT
    ROW_NUMBER() OVER (ORDER BY OT.ID_OT, P.PASO) AS ID_EVENTO,
    OT.ID_OT,
    P.ESTADO,
    DATEADD(HOUR, (P.PASO - 1) * (1 + OT.ID_OT % 7), OT.FECHA_CREACION) AS FECHA_ESTADO
FROM dbo.ordenes_trabajo_facts AS OT
JOIN PASOS AS P
    ON P.PASO <= CASE OT.ESTADO WHEN 'CERRADA' THEN 5 WHEN 'EN CURSO' THEN 4 ELSE 2 END
WHERE P.PASO <> 3 OR OT.ID_OT % 5 = 0;

WITH DIAS AS (
    SELECT TOP (365) DATEADD(DAY, -ROW_NUMBER() OVER (ORDER BY (SELECT NULL)), CAST('2026-10-31' AS DATE)) AS FECHA
    FROM sys.all_objects
),
FRANJAS AS (
    SELECT FRANJA
    FROM (VALUES ('08-12'), ('12-16'), ('16-20')) AS F (FRANJA)
)
INSERT INTO dbo.capacidad_agenda_facts (ID_CAPACIDAD, FECHA, ID_ZONA, FRANJA, CUPOS_TOTALES, CUPOS_OCUPADOS)
SELECT
    ROW_NUMBER() OVER (ORDER BY D.FECHA, Z.ID_ZONA, F.FRANJA) AS ID_CAPACIDAD,
    D.FECHA,
    Z.ID_ZONA,
    F.FRANJA,
    20 AS CUPOS_TOTALES,
    ABS(CHECKSUM(NEWID())) % 21 AS CUPOS_OCUPADOS
FROM DIAS AS D
CROSS JOIN dbo.dsc_zona_geografica AS Z
CROSS JOIN FRANJAS AS F;
